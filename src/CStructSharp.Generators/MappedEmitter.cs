namespace CStructSharp.Generators;

using System.Collections.Generic;

/// <summary>Writes the <c>ICStructMapped&lt;TSelf&gt;</c> implementation of one <c>[CStructMapped]</c> type.</summary>
internal static class MappedEmitter
{
    private const string Mapped = "global::CStructSharp.MappedTypes";

    public static string Emit(MappedRequest request, IReadOnlyList<string>? layoutMembers)
    {
        var writer = new SourceWriter();
        string name = request.ClassName;
        string contract = "global::CStructSharp.ICStructMapped<" + name + ">";
        writer.Line("// <auto-generated/>");
        writer.Line("// Generated by CStructSharp from the [CStructMapped] attribute on " + name + ". Do not edit.");
        writer.Line("#nullable enable");
        writer.Line("#pragma warning disable");
        writer.Line();
        if (request.Namespace is not null)
        {
            writer.Open("namespace " + request.Namespace);
        }

        foreach (ContainingType container in request.ContainingTypes)
        {
            writer.Open("partial " + container.Keyword + " " + container.Name);
        }

        writer.Line("[global::System.CodeDom.Compiler.GeneratedCode(\"CStructSharp\", \"" + typeof(MappedEmitter).Assembly.GetName().Version + "\")]");
        writer.Open(request.Accessibility + " partial " + request.TypeKeyword + " " + name + " : " + contract);

        writer.Line("/// <summary>Creates a <see cref=\"" + name + "\"/> from a parsed struct: every mapped property is read by name with the conversions of <c>Get&lt;T&gt;</c>.</summary>");
        writer.Line("/// <param name=\"source\">The parsed struct.</param>");
        writer.Line("/// <returns>The mapped instance.</returns>");
        writer.Open("public static " + name + " ReadFrom(global::CStructSharp.Values.StructValue source)");
        writer.Line("global::System.ArgumentNullException.ThrowIfNull(source);");
        writer.Line("return new " + name);
        writer.Line("{");
        writer.Indent();
        foreach (MappedMember member in request.Members)
        {
            writer.Line(member.PropertyName + " = " + Read(member, MemberName(member, layoutMembers, "source")) + ",");
        }

        writer.Outdent();
        writer.Line("};");
        writer.Close();
        writer.Line();
        writer.Line("/// <summary>Copies every mapped property into <paramref name=\"target\"/>, a struct of the layout's shape, by name.</summary>");
        writer.Line("/// <param name=\"value\">The instance to write.</param>");
        writer.Line("/// <param name=\"target\">The struct the writer serializes.</param>");
        writer.Open("public static void WriteTo(" + name + " value, global::CStructSharp.Values.StructValue target)");
        writer.Line("global::System.ArgumentNullException.ThrowIfNull(value);");
        writer.Line("global::System.ArgumentNullException.ThrowIfNull(target);");
        foreach (MappedMember member in request.Members)
        {
            Write(writer, member, MemberName(member, layoutMembers, "target"));
        }

        writer.Close();
        writer.Line();
        writer.Line("/// <summary>Registers the mapper before any code of the assembly runs, so <c>Get&lt;" + name + "&gt;</c>, <c>ReadValue&lt;" + name + "&gt;</c>, and the writers find it (also under Native AOT, where a static constructor might never run).</summary>");
        writer.Line("[global::System.Runtime.CompilerServices.ModuleInitializer]");
        writer.Line("internal static void RegisterCStructMapping() => " + Mapped + ".Register<" + name + ">();");
        writer.Close();

        for (int index = 0; index < request.ContainingTypes.Count; index++)
        {
            writer.Close();
        }

        if (request.Namespace is not null)
        {
            writer.Close();
        }

        return writer.ToString();
    }

    /// <summary>The member name expression: a literal when the layout resolved it or the attribute named it; otherwise the runtime's name match over the value's members.</summary>
    private static string MemberName(MappedMember member, IReadOnlyList<string>? layoutMembers, string value)
    {
        if (member.LayoutName is not null)
        {
            return SourceWriter.Literal(member.LayoutName);
        }

        if (layoutMembers is not null && CStructMappedGenerator.ResolveLayoutName(member, layoutMembers) is { } resolved)
        {
            return SourceWriter.Literal(resolved);
        }

        return Mapped + ".MemberName(" + value + ", " + SourceWriter.Literal(member.PropertyName) + ")";
    }

    private static string Read(MappedMember member, string name)
    {
        string read = member.Kind switch
        {
            MappedMemberKind.List => "new global::System.Collections.Generic.List<" + member.ElementTypeName + ">(source.Get<" + member.ElementTypeName + "[]>(" + name + "))",
            MappedMemberKind.ReadOnlyCollection => "source.Get<" + member.ElementTypeName + "[]>(" + name + ")",
            MappedMemberKind.TypedPointer => member.TypeName + ".FromPointer(source.Get<global::CStructSharp.Values.Pointer>(" + name + "), static target => " + Mapped + ".ConvertValue<" + member.ElementTypeName + ">(target, " + name + "))",
            _ => "source.Get<" + member.TypeName + ">(" + name + ")",
        };
        if (member.IsNullableValue)
        {
            // A nullable value type reads null for a member the parse did not produce (an unselected conditional arm).
            return "source.TryGetValue(" + name + ", out _) ? " + read + " : null";
        }

        return read;
    }

    private static void Write(SourceWriter writer, MappedMember member, string name)
    {
        string access = "value." + member.PropertyName;
        if (member.IsNullableValue)
        {
            writer.Open("if (" + access + " is { } " + Local(member) + ")");
            writer.Line("target[" + name + "] = " + (member.Kind == MappedMemberKind.TypedPointer ? Local(member) + ".ToPointer(static target => target!)" : Local(member)) + ";");
            writer.Close();
            return;
        }

        writer.Line("target[" + name + "] = " + (member.Kind == MappedMemberKind.TypedPointer ? access + ".ToPointer(static target => target!)" : access) + ";");
    }

    private static string Local(MappedMember member) => char.ToLowerInvariant(member.PropertyName[0]) + member.PropertyName.Substring(1) + "Value";
}
